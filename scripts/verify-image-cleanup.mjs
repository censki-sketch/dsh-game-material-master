/** Real wire/gateway, synthetic pixels, isolated storage. All network is forbidden. */
import assert from 'node:assert/strict';
import {mkdtemp, readFile, readdir, rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join, resolve, dirname, basename} from 'node:path';
const home = await mkdtemp(join(tmpdir(), 'gmm-image-cleanup-'));
process.env.DSH_HOME = home;
const {Context} = await import('@deepseek-ai/cordis');
const plugin = await import('../lib/index.js'), wire = await import('../lib/wire.js');
const imagegen = await import('../lib/imagegen.js');
const {keyGreen, cleanImageRegions} = await import('../lib/chroma.js');
const {encodePng} = await import('../lib/png.js');
const {decodeToRgba} = await import('../lib/media.js');
const originalFetch = globalThis.fetch;
let requests = 0;
globalThis.fetch = () => { requests++; throw Error('Network forbidden in local cleanup checks'); };
const ctx = new Context();
for (const name of ['typert', 'webServer', 'tools']) ctx.provide(name, {register: () => () => {}});
ctx.provide('systemPrompt', {section: () => () => {}});
plugin.apply(ctx);
const gateway = ctx.get('gameStudio');
const invoke = async (method, payload) => {
  const spec = wire.METHODS.find(m => m.method === method);
  const parsed = spec.payload.parse(payload);
  assert.deepEqual(parsed, payload, 'wire must retain every point and version field');
  return spec.result.parse(await gateway[method](parsed));
};
let checks = 0;
const check = (name, value) => { assert.ok(value, name); checks++; console.log('✓ ' + name); };
try {
  const size = 192, rgba = Buffer.alloc(size * size * 4), screen = [255, 0, 255], hair = [80, 44, 24];
  const put = (x, y, color) => { const p = (y * size + x) * 4; rgba.set([...color, 255], p); };
  for (let y = 0; y < size; y++) for (let x = 0; x < size; x++) put(x, y, screen);
  for (let y = 15; y < 177; y++) for (let x = 15; x < 177; x++) put(x, y, hair);
  for (let y = 70; y < 74; y++) for (let x = 70; x < 74; x++) {
    const alpha = 0.3 + (x - 70) * 0.1;
    put(x, y, hair.map((v, c) => Math.round(v * alpha + screen[c] * (1 - alpha))));
  }
  for (let y = 100; y < 104; y++) for (let x = 100; x < 104; x++) put(x, y, [170, 35, 170]);
  for (let y = 110; y < 142; y++) for (let x = 110; x < 142; x++) put(x, y, [170, 35, 170]);
  const options = {keyColor: '#FF00FF', keyLow: 14, keyHigh: 80, despill: 0.75, bgTolerance: 90, edgeShrink: 0};
  const legacy = keyGreen(rgba, size, size, options).rgba;
  const refined = keyGreen(rgba, size, size, {...options, refineEdges: true}).rgba;
  const gap = (71 * size + 71) * 4;
  check('closed mixed-color gap reproduces opaque purple residue', legacy[gap + 3] === 255 && legacy[gap + 2] - legacy[gap + 1] > 80);
  check('closed gap recovers its local foreground color and coverage', Math.abs(refined[gap + 3] - 102) < 3 && hair.every((v, c) => Math.abs(refined[gap + c] - v) < 3));
  check('small intentional purple ornament remains unchanged', [100, 101, 102, 103].every(y => [100, 101, 102, 103].every(x => {const p = (y * size + x) * 4; return refined.subarray(p, p + 4).equals(rgba.subarray(p, p + 4));})));
  check('large purple garment keeps a stable opaque core', refined.subarray((120 * size + 120) * 4, (120 * size + 120) * 4 + 4).equals(rgba.subarray((120 * size + 120) * 4, (120 * size + 120) * 4 + 4)));
  check('video/default path remains unchanged and source buffer is immutable', keyGreen(rgba, size, size, options).rgba.equals(legacy) && rgba[gap + 3] === 255);
  const small = Buffer.alloc(9 * 7 * 4);
  for (let p = 0; p < small.length; p += 4) small.set([100, 50, 20, 255], p);
  for (const [x, y] of [[0, 0], [1, 0], [0, 1], [1, 1], [2, 0], [6, 5]]) small.set([190, 8, 160, 255], (y * 9 + x) * 4);
  const cleaned = cleanImageRegions(small, 9, 7, [{x: 0, y: 0, radius: 1, tolerance: 10}]);
  check('corner selection uses true pixel coordinates and bounded radius', cleaned.changedPixels === 3 && cleaned.rgba[3] === 0 && cleaned.rgba[7] === 0 && cleaned.rgba[(1 * 9) * 4 + 3] === 0);
  check('same-color pixels outside radius or disconnected are preserved', cleaned.rgba[(1 * 9 + 1) * 4 + 3] === 255 && cleaned.rgba[(5 * 9 + 6) * 4 + 3] === 255);
  check('manual selection never mutates input RGB or alpha', small[3] === 255 && cleaned.rgba.subarray(0, 3).equals(small.subarray(0, 3)));
  assert.throws(() => cleanImageRegions(small, 9, 7, [{x: 9, y: 0, radius: 1, tolerance: 10}]), /无效/);
  assert.throws(() => cleanImageRegions(small, 9, 7, [{x: 0, y: 0, radius: 65, tolerance: 10}]), /无效/);
  assert.throws(() => cleanImageRegions(small, 9, 7, []), /点选/);
  check('invalid dimensions, ranges and empty selection fail before output', true);
  const {jobId} = await invoke('createImageJob', {name: 'offline cleanup fixture'});
  const input = encodePng(rgba, size, size);
  await invoke('saveImageJob', {jobId, keying: {enabled: true, ...options}});
  await invoke('addImageItem', {jobId, name: 'synthetic.png', data: input.toString('base64')});
  const job = await imagegen.readImageJob(jobId), item = job.items[0];
  const file = imagegen.imageAssetPath(jobId, item.file), keyed = imagegen.imageAssetPath(jobId, item.keyedFile);
  const oldKeyed = await readFile(keyed), oldJob = await readFile(join(imagegen.imageJobDir(jobId), 'job.json'));
  const files = await readdir(join(imagegen.imageJobDir(jobId), 'keyed'));
  const payload = {jobId, index: 0, versionId: item.versionId, points: [{x: 101, y: 101, radius: 8, tolerance: 16}], action: 'preview'};
  const preview = await invoke('cleanImageRegion', payload);
  check('preview returns an actual local PNG and selected pixel count', preview.preview.startsWith('data:image/png;base64,') && preview.changedPixels === 16);
  check('preview writes no files, history, timestamps or parameters', (await readFile(join(imagegen.imageJobDir(jobId), 'job.json'))).equals(oldJob) && JSON.stringify(await readdir(join(imagegen.imageJobDir(jobId), 'keyed'))) === JSON.stringify(files));
  await assert.rejects(invoke('cleanImageRegion', {...payload, versionId: 'stale'}), /版本已变化/);
  await assert.rejects(invoke('cleanImageRegion', {...payload, points: [{x: 192, y: 0, radius: 8, tolerance: 16}]}), /无效/);
  check('stale version and real decoded image bounds are checked', true);
  const savePayload = {...payload, action: 'save'};
  const saves = await Promise.allSettled([invoke('cleanImageRegion', savePayload), invoke('cleanImageRegion', savePayload)]);
  check('concurrent saves create one version and reject stale duplicate', saves.filter(r => r.status === 'fulfilled').length === 1 && saves.some(r => r.status === 'rejected' && /版本已变化/.test(r.reason.message)));
  const saved = await imagegen.readImageJob(jobId), next = saved.items[0];
  check('save appends a new history version and resets approval', saved.history.length === 2 && next.versionId !== item.versionId && next.keyedFile !== item.keyedFile && next.approved === false && saved.history.at(-1).cleanup.sourceVersionId === item.versionId);
  check('local cleanup remains in the uploaded image conversation', next.roundId === item.roundId && saved.history.at(-1).roundId === item.roundId && next.roundId === saved.history[0].roundId);
  check('original and previous keyed bytes survive unchanged', (await readFile(file)).equals(input) && (await readFile(keyed)).equals(oldKeyed));
  const decoded = await decodeToRgba(imagegen.imageAssetPath(jobId, next.keyedFile));
  check('saved pixels exactly match host preview PNG', encodePng(decoded.rgba, decoded.width, decoded.height).toString('base64') === preview.preview.split(',')[1]);
  await invoke('manageImageHistory', {jobId, historyId: item.versionId, action: 'restore'});
  check('old result can be restored from history', (await imagegen.readImageJob(jobId)).items[0].keyedFile === item.keyedFile);
  await imagegen.editImageJob(jobId, current => { current.items[0].status = 'running'; });
  await assert.rejects(invoke('cleanImageRegion', payload), /正在处理/);
  check('running item blocks local editing', true);
  const schema = wire.METHODS.find(m => m.method === 'cleanImageRegion').payload;
  for (const patch of [{index: -1}, {versionId: ''}, {action: 'generate'}, {points: []}, {points: Array(101).fill(payload.points[0])}, {points: [{...payload.points[0], x: 0.5}]}, {points: [{...payload.points[0], tolerance: 161}]}]) assert.equal(schema.safeParse({...payload, ...patch}).success, false);
  check('wire rejects invalid indices, versions, actions, fractional points and excessive input', true);
  check('upload, automatic keying, preview, save and restore use zero network requests', requests === 0);
  console.log(`Passed ${checks} local image cleanup checks. No network or real credentials.`);
} finally {
  globalThis.fetch = originalFetch;
  assert.equal(dirname(resolve(home)), resolve(tmpdir()));
  assert.ok(basename(home).startsWith('gmm-image-cleanup-'));
  await rm(home, {recursive: true, force: true});
}
